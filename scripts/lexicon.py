    plural={'ფურცელი':'ფურცლები','ფანქარი':'ფანქრები','ჩანგალი':'ჩანგლები','ფიცარი':'ფიცრები','კალამი':'კალმები','მიზანი':'მიზნები','დერეფანი':'დერეფნები','ნაჭერი':'ნაჭრები'}.get(nom,plural)
    if nom=='ტანსაცმელი':return Noun(nom,dat,nom,dat,domain,category)
    return Noun(nom,dat,plural,plural[:-1]+'ს',domain,category)


def object_phrase(n,a,case='nom',plural=False):
    adj=a[1] if case=='dat' else a[0]
    form=(n.plural_dat if case=='dat' else n.plural) if plural else (n.dat if case=='dat' else n.nom)
    return adj+' '+form

def actor_form(a,case='nom',plural=False):
    if plural:return a.plural_erg if case=='erg' else a.plural_dat if case=='dat' else a.plural
    return a.erg if case=='erg' else a.dat if case=='dat' else a.nom
